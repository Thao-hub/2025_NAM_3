SELECT *
FROM VEXE
WHERE EXTRACT(MONTH FROM NGMUA) = 12
ORDER BY GIAVE DESC;

SELECT MATUYEN, COUNT(*) AS SOLUONG
FROM VEXE
WHERE EXTRACT(YEAR FROM NGMUA) = 2016
GROUP BY MATUYEN
HAVING COUNT(*) = (
    SELECT MIN(COUNT(*))
    FROM VEXE
    WHERE EXTRACT(YEAR FROM NGMUA) = 2016
    GROUP BY MATUYEN
);

SELECT V.MATUYEN
FROM VEXE V
JOIN KHACH K ON V.MAHK = K.MAHK
GROUP BY V.MATUYEN
HAVING
    SUM(CASE WHEN K.GIOITINH = 'Nam' THEN 1 ELSE 0 END) > 0
AND
    SUM(CASE WHEN K.GIOITINH = 'Nu' THEN 1 ELSE 0 END) > 0;

SELECT K.MAHK, K.HOTEN
FROM KHACH K
WHERE K.GIOITINH = 'Nu'
AND NOT EXISTS (
    SELECT *
    FROM TUYEN T
    WHERE NOT EXISTS (
        SELECT *
        FROM VEXE V
        WHERE V.MATUYEN = T.MATUYEN
        AND V.MAHK = K.MAHK
    )
);

