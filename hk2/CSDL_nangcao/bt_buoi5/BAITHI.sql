CREATE OR REPLACE TRIGGER TRG_TANG_GIA
BEFORE INSERT OR UPDATE ON TUYEN
FOR EACH ROW
BEGIN
    IF :NEW.NGXB BETWEEN
       DATE '2016-12-29'
       AND
       DATE '2017-01-05'
    THEN
        :NEW.GIATUYEN := :NEW.GIATUYEN * 1.2;
    END IF;
END;
