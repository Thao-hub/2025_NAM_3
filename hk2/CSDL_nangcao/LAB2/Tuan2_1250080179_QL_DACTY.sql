    MANV      CHAR(9) CONSTRAINT PK_NHANVIEN PRIMARY KEY,
    HONV      NVARCHAR2(15) NOT NULL,
    TENLOT    NVARCHAR2(15),
    TENNV     NVARCHAR2(15) NOT NULL,
    NGSINH    DATE,
    DCHI      NVARCHAR2(100),
    PHAI      NVARCHAR2(3),
    LUONG     NUMBER(12,0),
    MA_NQL    CHAR(9),
    PHG       NUMBER(2),
    CONSTRAINT FK_NV_NQL FOREIGN KEY (MA_NQL) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_NV_PHG FOREIGN KEY (PHG) REFERENCES PHONGBAN(MAPHG)
);

