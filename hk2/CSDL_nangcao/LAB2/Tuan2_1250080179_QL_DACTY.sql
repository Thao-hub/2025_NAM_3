CREATE TABLE DIADIEM_PHG (
    MAPHG      NUMBER(2) NOT NULL,
    DIADIEM    NVARCHAR2(30) NOT NULL,
    CONSTRAINT PK_DIADIEM_PHG PRIMARY KEY (MAPHG, DIADIEM),
    CONSTRAINT FK_DD_PHG FOREIGN KEY (MAPHG) REFERENCES PHONGBAN(MAPHG)
);

CREATE TABLE DEAN (
    MADA        NUMBER(3) CONSTRAINT PK_DEAN PRIMARY KEY,
    TENDA       NVARCHAR2(50) NOT NULL,
    DDIEM_DA    NVARCHAR2(30),
    PHONG       NUMBER(2) NOT NULL,
    CONSTRAINT FK_DEAN_PHONG FOREIGN KEY (PHONG) REFERENCES PHONGBAN(MAPHG)
);

CREATE TABLE PHANCONG (
    MA_NVIEN   CHAR(9) NOT NULL,
    SODA       NUMBER(3) NOT NULL,
    THOIGIAN   NUMBER(5,1) NOT NULL,
    CONSTRAINT PK_PHANCONG PRIMARY KEY (MA_NVIEN, SODA),
    CONSTRAINT FK_PC_NV FOREIGN KEY (MA_NVIEN) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_PC_DA FOREIGN KEY (SODA) REFERENCES DEAN(MADA)
);

CREATE TABLE THANNHAN (
    MA_NVIEN    CHAR(9) NOT NULL,
    TENTN       NVARCHAR2(30) NOT NULL,
    PHAI        NVARCHAR2(3),
    NGSINH      DATE,
    QUANHE      NVARCHAR2(20),
    CONSTRAINT PK_THANNHAN PRIMARY KEY (MA_NVIEN, TENTN),
    CONSTRAINT FK_TN_NV FOREIGN KEY (MA_NVIEN) REFERENCES NHANVIEN(MANV)
);


